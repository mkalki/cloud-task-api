CREATE TABLE jobs (
    id               UUID PRIMARY KEY,
    owner_id         BIGINT       NOT NULL,
    -- No foreign key yet: the workflows table is created in F5, which adds the constraint.
    workflow_id      UUID,
    type             VARCHAR(100) NOT NULL,
    payload          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    priority         SMALLINT     NOT NULL DEFAULT 5,
    status           VARCHAR(20)  NOT NULL,
    attempt          INT          NOT NULL DEFAULT 0,
    max_attempts     INT          NOT NULL DEFAULT 3,
    timeout_seconds  INT          NOT NULL DEFAULT 300,
    run_at           TIMESTAMPTZ  NOT NULL,
    pending_parents  INT          NOT NULL DEFAULT 0,
    locked_by        VARCHAR(100),
    lease_expires_at TIMESTAMPTZ,
    idempotency_key  VARCHAR(255),
    last_error       TEXT,
    started_at       TIMESTAMPTZ,
    finished_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    version          BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT fk_jobs_owner
        FOREIGN KEY (owner_id) REFERENCES users (id),

    CONSTRAINT chk_jobs_status
        CHECK (status IN ('BLOCKED', 'PENDING', 'QUEUED', 'RUNNING',
                          'SUCCEEDED', 'DEAD', 'CANCELLED', 'UPSTREAM_FAILED')),
    CONSTRAINT chk_jobs_priority
        CHECK (priority BETWEEN 0 AND 9),
    CONSTRAINT chk_jobs_max_attempts
        CHECK (max_attempts BETWEEN 1 AND 10),
    CONSTRAINT chk_jobs_timeout_seconds
        CHECK (timeout_seconds BETWEEN 1 AND 3600),
    CONSTRAINT chk_jobs_attempt
        CHECK (attempt >= 0),
    CONSTRAINT chk_jobs_pending_parents
        CHECK (pending_parents >= 0)
);

CREATE INDEX idx_jobs_status_run_at ON jobs (status, run_at);
CREATE INDEX idx_jobs_owner_created ON jobs (owner_id, created_at);
CREATE INDEX idx_jobs_workflow ON jobs (workflow_id);

-- One job per (owner, Idempotency-Key). Jobs without a key are unconstrained.
CREATE UNIQUE INDEX uq_jobs_owner_idempotency_key
    ON jobs (owner_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL;

CREATE TABLE job_attempts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      UUID        NOT NULL,
    attempt_no  INT         NOT NULL,
    worker_id   VARCHAR(100),
    started_at  TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    outcome     VARCHAR(20),
    error       TEXT,
    duration_ms BIGINT,

    CONSTRAINT fk_job_attempts_job
        FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,

    -- outcome stays NULL while an attempt is in flight.
    CONSTRAINT chk_job_attempts_outcome
        CHECK (outcome IS NULL
               OR outcome IN ('SUCCEEDED', 'FAILED', 'TIMEOUT', 'WORKER_LOST', 'FENCED'))
);

-- Not unique on (job_id, attempt_no): a fenced late result from a stale worker
-- is recorded as its own row for the same attempt number.
CREATE INDEX idx_job_attempts_job ON job_attempts (job_id, attempt_no);
